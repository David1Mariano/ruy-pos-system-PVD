package br.com.ruy.pos.backup

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

class BackupManagerSimulatedTest {
    @Test
    fun sqliteMagicBytesRecognized() {
        val magic = byteArrayOf(
            0x53, 0x51, 0x4C, 0x69, 0x74, 0x65, 0x20, 0x66,
            0x6F, 0x72, 0x6D, 0x61, 0x74, 0x20, 0x33, 0x00
        )
        assertEquals(16, magic.size)
        assertTrue(magic.contentEquals(byteArrayOf(0x53, 0x51, 0x4C, 0x69, 0x74, 0x65, 0x20, 0x66, 0x6F, 0x72, 0x6D, 0x61, 0x74, 0x20, 0x33, 0x00)))
    }

    @Test
    fun corruptedZipIsRejected() {
        val bad = byteArrayOf(0x00, 0x01, 0x02, 0x03)
        // A 4-byte file is not a valid SQLite header.
        assertFalse(bad.contentEquals(byteArrayOf(0x53, 0x51, 0x4C, 0x69, 0x74, 0x65, 0x20, 0x66, 0x6F, 0x72, 0x6D, 0x61, 0x74, 0x20, 0x33, 0x00)))
    }
}